/** Puts the dev admin back to its original password with a forced change pending (so every run starts identically, even after a crashed run, and ends that way too). */
async function resetDevAdmin() {
  const url = process.env.DATABASE_URL ?? ''
  if (!/127.0.0.1|localhost/.test(url)) throw new Error('E2E resets the admin password: refusing to run against a non-local database')
  const c = new pg.Client({ connectionString: url }); await c.connect()
  await c.query('update users set password_hash = $1, must_change_password = true, password_changed_at = now() where email = $2', [await hash(ADMIN_PASSWORD), ADMIN_EMAIL.toLowerCase()])
  await c.end()
}

/** Local only: a platform admin for the console steps. */
async function setPlatformUser(email: string, pw: string) {
  const url = process.env.DATABASE_URL ?? ''
  if (!/127.0.0.1|localhost/.test(url)) throw new Error('refusing to add a platform admin on a non-local database')
  const c = new pg.Client({ connectionString: url }); await c.connect()
  await c.query(`insert into platform_users (name, email, password_hash) values ('E2E Platform', $1, $2)
    on conflict (lower(email)) do update set password_hash = excluded.password_hash, is_active = true`, [email, await hash(pw)])
  await c.end()
}

/** Local only: the one-time password the student would get by e-mail (e-mail is off in test runs), with a change forced. */
async function setTempPassword(email: string, pw: string) {
  const url = process.env.DATABASE_URL ?? ''
  if (!/127.0.0.1|localhost/.test(url)) throw new Error('refusing to set a password on a non-local database')
  const c = new pg.Client({ connectionString: url }); await c.connect()
  const r = await c.query('update users set password_hash = $1, must_change_password = true, password_changed_at = now() where lower(email) = $2', [await hash(pw), email.toLowerCase()])
  await c.end()
  if (r.rowCount !== 1) throw new Error(`no login for ${email}`)
}

