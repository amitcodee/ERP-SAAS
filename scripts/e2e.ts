/** Each section is its own page now: click its link and wait for that page to load. */
async function go(page: Page, label: string) {
  const link = nav(page, label)
  const href = await link.getAttribute('href')
  await link.click()
  if (href) await page.waitForURL((u) => u.pathname === href, { timeout: 20000 })
  await page.waitForLoadState('networkidle')
}
const SIGNED_IN = (u: URL) => u.pathname === '/' || u.pathname === '/dashboard'
async function ok(name: string, fn: () => Promise<void>, page?: Page) {
  step = name
  try { await fn(); log(true, name) }
  catch (e) {
    log(false, name)
    if (page) await page.screenshot({ path: `${OUT}/FAIL-${name.replace(/\W+/g, '_').slice(0, 50)}.png`, fullPage: true }).catch(() => {})
    console.error(String((e as Error).message).split('\n').slice(0, 6).join('\n'))
    throw e
  }
}

const NEW_PW = (who: string) => `Chosen-${who}-${RUN}-9x`
/** Signs in. If the account must choose a new password first, does that too. Returns the password that works from now on. */
async function login(browser: Browser, email: string, password: string, who = 'user'): Promise<{ ctx: BrowserContext; page: Page; password: string }> {
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  const page = await ctx.newPage()
  page.setDefaultTimeout(20000)
  await page.goto(`${BASE}/login`, { waitUntil: 'networkidle' })
  await page.getByLabel('Email').fill(email)
  await page.locator('input[name="password"]').fill(password)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await page.waitForURL(SIGNED_IN, { timeout: 20000 })
  await page.waitForLoadState('networkidle')
  let finalPw = password
  if (await page.getByText('Set a new password').first().isVisible().catch(() => false)) {
    finalPw = NEW_PW(who)
    await page.getByLabel('Current password').fill(password)
    await page.getByLabel('New password', { exact: true }).fill(finalPw)
    await page.getByLabel('Repeat new password').fill(finalPw)
    await page.getByRole('button', { name: 'Change password' }).click()
    await page.locator('a.nav-item, main h1, header.pt-bar').first().waitFor({ state: 'visible', timeout: 20000 })
    await page.waitForLoadState('networkidle')
  }
  return { ctx, page, password: finalPw }
}

